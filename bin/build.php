#!/usr/bin/env php
<?php
/**
 * Build dist/open-consent.js from the ES modules in packages/web/src — no Node needed.
 *
 *   php bin/build.php          build + copy into the WordPress plugin
 *   php bin/build.php --check  fail if the committed dist/ is stale
 *
 * Module rules the bundler relies on (enforced, build fails otherwise):
 *  - imports are single-line `import { a, b } from './x.js';` (no `* as`, no `as` renames)
 *  - exports are `export function|const|let|class name` (no default / re-exports)
 *  - top-level names are unique across all modules
 */
declare(strict_types=1);

$root = dirname(__DIR__);
$check = in_array('--check', $argv, true);
$version = trim((string) file_get_contents("$root/VERSION"));
if (!preg_match('/^\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?$/', $version)) {
    fwrite(STDERR, "VERSION is not semver: $version\n");
    exit(1);
}

$ORDER = [
    'generated/defaults.js', 'util.js', 'config.js', 'consent-policy.js', 'consent-state.js',
    'storage.js', 'events.js', 'i18n.js', 'google-consent.js', 'dom.js', 'accessibility.js',
    'script-blocker.js', 'banner.js', 'preferences.js', 'ui.js', 'embed.js', 'index.js',
];

function fail(string $m): never
{
    fwrite(STDERR, "build: $m\n");
    exit(1);
}

/** @return list<string> sorted dotted key paths of string leaves */
function keyPaths(mixed $data, string $prefix = ''): array
{
    $out = [];
    foreach ((array) $data as $k => $v) {
        if (is_array($v)) $out = array_merge($out, keyPaths($v, "$prefix$k."));
        elseif (is_string($v) && $v !== '') $out[] = "$prefix$k";
        else fail("translation value at $prefix$k must be a non-empty string");
    }
    sort($out);
    return $out;
}

function readJson(string $path): mixed
{
    $raw = file_get_contents($path);
    if ($raw === false) fail("cannot read $path");
    try {
        return json_decode($raw, true, 64, JSON_THROW_ON_ERROR);
    } catch (JsonException $e) {
        fail("$path: " . $e->getMessage());
    }
}

// 1. Generated module: defaults + translations + CSS + version (single source: config/ + styles/).
$policy = readJson("$root/config/default-policy.json");
// Only these languages are compiled into the bundle (size). Every other file in
// config/translations/ is shipped as JSON and injected via config.texts by the
// PHP library / WordPress plugin (Translations::forLocale()).
$BUILTIN_LANGS = ['en', 'id'];
$translations = [];
$enKeys = null;
foreach (glob("$root/config/translations/*.json") ?: [] as $f) {
    $code = basename($f, '.json');
    if (!preg_match('/^[a-z]{2,3}$/', $code)) fail("translation file name must be a language code: $code");
    $data = readJson($f);
    $keys = keyPaths($data);
    if ($enKeys === null) $enKeys = keyPaths(readJson("$root/config/translations/en.json"));
    if ($keys !== $enKeys) fail("config/translations/$code.json keys differ from en.json: " . implode(', ', array_merge(array_diff($enKeys, $keys), array_diff($keys, $enKeys))));
    if (in_array($code, $BUILTIN_LANGS, true)) $translations[$code] = $data;
}
ksort($translations);
if (!isset($translations['en'])) fail('config/translations/en.json is required');
$css = (string) file_get_contents("$root/packages/web/styles/open-consent.css");
$css = preg_replace('~/\*.*?\*/~s', '', $css);
$css = trim(preg_replace('/\s*\n\s*/', "\n", $css));
$j = JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR;
$generated = "// GENERATED by bin/build.php from config/ and packages/web/styles/ — do not edit.\n"
    . 'export const VERSION = ' . json_encode($version) . ";\n"
    . 'export const DEFAULT_POLICY = ' . json_encode($policy, $j) . ";\n"
    . 'export const TRANSLATIONS = ' . json_encode($translations, $j) . ";\n"
    . 'export const CSS = ' . json_encode($css, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . ";\n";
$genPath = "$root/packages/web/src/generated/defaults.js";

// 2. Concatenate modules.
$seen = [];
$body = '';
foreach ($ORDER as $mod) {
    $path = "$root/packages/web/src/$mod";
    $src = $mod === 'generated/defaults.js' ? $generated : file_get_contents($path);
    if ($src === false) fail("missing module $mod");
    $out = [];
    foreach (explode("\n", $src) as $n => $line) {
        $ln = $n + 1;
        if (preg_match('/^import\b/', $line)) {
            if (!preg_match("/^import \{ [A-Za-z0-9_$, ]+ \} from '\.\/[a-z0-9\/.-]+\.js';$/", $line) || str_contains($line, ' as ')) {
                fail("$mod:$ln unsupported import form: $line");
            }
            continue;
        }
        if (preg_match('/^export\s+(default|\{|\*)/', $line)) fail("$mod:$ln unsupported export form");
        $line = preg_replace('/^export (function|const|let|class) /', '$1 ', $line);
        if (preg_match('/^(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/', $line, $m)) {
            if (isset($seen[$m[1]])) fail("$mod:$ln top-level name '{$m[1]}' already declared in {$seen[$m[1]]}");
            $seen[$m[1]] = $mod;
        }
        $out[] = $line;
    }
    $body .= "\n// ---- $mod ----\n" . rtrim(implode("\n", $out)) . "\n";
}
foreach (glob("$root/packages/web/src/*.js") ?: [] as $f) {
    if (!in_array(basename($f), $ORDER, true)) fail('module ' . basename($f) . ' is not listed in $ORDER');
}

$bundle = "/*! OpenConsent v$version | GPL-2.0-or-later | https://seoultra.id/plugins/open-consent/ */\n"
    . "(function (window, document) {\n'use strict';\nif (!window || !document) return;\n"
    . $body
    . "\ninstall(window, document);\n})(typeof window !== 'undefined' ? window : null, typeof document !== 'undefined' ? document : null);\n";
$sri = 'sha384-' . base64_encode(hash('sha384', $bundle, true));

$targets = [
    $genPath => $generated,
    "$root/dist/open-consent.js" => $bundle,
    "$root/dist/open-consent.js.sri" => $sri . "\n",
    "$root/integrations/wordpress/open-consent/assets/js/open-consent.js" => $bundle,
];

// The WordPress plugin ships its own copy of the PHP library + default policy.
$wp = "$root/integrations/wordpress/open-consent";
foreach (glob("$root/config/translations/*.json") ?: [] as $f) {
    $targets["$wp/config/translations/" . basename($f)] = (string) file_get_contents($f);
}
$targets["$wp/config/default-policy.json"] = json_encode($policy, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR) . "\n";
$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator("$root/packages/core-php/src", FilesystemIterator::SKIP_DOTS));
foreach ($it as $f) {
    if ($f->getExtension() !== 'php' || str_contains($f->getPathname(), '/Hosted/')) continue;
    $rel = substr($f->getPathname(), strlen("$root/packages/core-php/src/"));
    $targets["$wp/lib/$rel"] = (string) file_get_contents($f->getPathname());
}
foreach (glob("$wp/lib/*.php") ?: [] as $f) {
    if (!isset($targets[$f])) {
        if ($check) fail('stale file ' . substr($f, strlen($root) + 1));
        unlink($f);
    }
}

if ($check) {
    $stale = [];
    foreach ($targets as $p => $c) {
        if (!is_file($p) || file_get_contents($p) !== $c) $stale[] = substr($p, strlen($root) + 1);
    }
    if ($stale) fail("stale build output, run php bin/build.php:\n  " . implode("\n  ", $stale));
    echo "build output is up to date (v$version)\n";
    exit(0);
}

foreach ($targets as $p => $c) {
    if (!is_dir(dirname($p))) mkdir(dirname($p), 0775, true);
    file_put_contents($p, $c);
}
printf("built dist/open-consent.js v%s (%s bytes, %s gzip) %s\n", $version, number_format(strlen($bundle)), number_format(strlen(gzencode($bundle, 9))), $sri);
